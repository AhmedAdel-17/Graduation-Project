const dictionaries: Record<Locale, Dict> = { en, ar };

const STORAGE_KEY = "egx-dashboard-locale";

function readPersisted(): Locale {
  if (typeof window === "undefined") return "en";
  const raw = window.localStorage.getItem(STORAGE_KEY);
  return raw === "ar" || raw === "en" ? raw : "en";
}

// Tiny external-store impl so any component can `useLocale()` without context.
let current: Locale = readPersisted();
const listeners = new Set<() => void>();

function emit() {
  listeners.forEach((l) => l());
}

function applyDocumentAttrs(locale: Locale) {
  if (typeof document === "undefined") return;
  document.documentElement.lang = locale;
  document.documentElement.dir = locale === "ar" ? "rtl" : "ltr";
}

export function setLocale(next: Locale) {
  if (next === current) return;
  current = next;
  if (typeof window !== "undefined") {
    window.localStorage.setItem(STORAGE_KEY, next);
  }
  applyDocumentAttrs(next);
  emit();
}

export function getLocale(): Locale {
  return current;
}

export function initI18n() {
  applyDocumentAttrs(current);
}

function subscribe(cb: () => void) {
  listeners.add(cb);
  return () => {
    listeners.delete(cb);
  };
}

export function useLocale(): Locale {
  return useSyncExternalStore(subscribe, getLocale, getLocale);
}

type TParams = Record<string, string | number>;

// Interpolates {token} placeholders in a resolved string. No-op when params
// is undefined, so existing single-arg t("key") callers are unaffected.
function interpolate(s: string, params?: TParams): string {
  if (!params) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) =>
    k in params ? String(params[k]) : m
  );
}

export function t(key: string, params?: TParams, locale: Locale = current): string {
  const raw = dictionaries[locale][key] ?? dictionaries.en[key] ?? key;
  return interpolate(raw, params);
}

export function useT(): (key: string, params?: TParams) => string {
  const locale = useLocale();
  return (key: string, params?: TParams) => t(key, params, locale);
}

/**
 * Translate a short agent-output enum token (e.g. "HOLD", "HIGH", "UPTREND") via
 * the `enum.<group>.<value>` dictionary keys. Falls back to the raw token when no
 * mapping exists — so English (which has no enum keys) keeps the raw value, and
 * unknown values pass through untouched. `translate` is the `useT()` function.
 */
export function tEnum(
  translate: (key: string) => string,
  group: string,
  value: string | null | undefined
): string {
  const v = (value ?? "").toString().trim();
  if (!v) return "—";
  const key = `enum.${group}.${v.toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(/^_+|_+$/g, "")}`;
  const out = translate(key);
  return out === key ? v : out;
}
