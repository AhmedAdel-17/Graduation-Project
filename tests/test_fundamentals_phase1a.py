class TestDataConfidence:

    def _full_income(self):
        return {
            "revenue": 1000.0, "gross_profit": 400.0,
            "operating_income": 200.0, "net_income": 100.0,
            "cost_of_revenue": 600.0, "ebitda": 220.0, "eps_basic": 5.0,
        }

    def _full_balance(self):
        return {
            "total_assets": 2000.0, "total_liabilities": 1200.0, "total_equity": 800.0,
            "cash_and_equivalents": 200.0, "current_assets": 500.0,
            "current_liabilities": 300.0, "long_term_debt": 500.0,
            "shares_outstanding": 20.0,
        }

    def _full_ratios(self):
        return {
            "pe_ratio": 10.0, "eps": 5.0, "debt_to_equity": 1.5,
            "current_ratio": 1.67, "roe": 0.125, "roa": 0.05,
            "gross_margin": 0.40, "net_margin": 0.10,
            "book_value_per_share": 40.0,
        }

    def test_full_data_high_confidence(self):
        score = compute_data_confidence(
            income_row=self._full_income(),
            balance_row=self._full_balance(),
            ratios_row=self._full_ratios(),
            n_annual_periods=5,
            periods_since_last_filing=0,
        )
        assert score > 80, f"Full data should yield > 80, got {score}"

    def test_partial_data_low_confidence(self):
        # Only income statement (4 of 7 required fields), no balance or ratios.
        # With field_coverage = 4/7 ≈ 0.57 and full staleness, formula gives ~54.
        # Key check: partial data confidence should be materially lower than full data (> 80).
        score = compute_data_confidence(
            income_row={"revenue": 1000.0, "gross_profit": 400.0,
                        "operating_income": 200.0, "net_income": 100.0},
            balance_row={},  # No balance sheet — 3 required fields missing
            ratios_row={},   # No ratios
            n_annual_periods=2,
            periods_since_last_filing=0,
        )
        assert score < 65, f"Partial data (no balance) should yield < 65, got {score}"
        # Also verify it is lower than the full-data score tested in test_full_data_high_confidence
        assert score < 80, f"Partial data should be < full data threshold (80), got {score}"

    def test_distress_does_not_lower_confidence(self):
        """A company with negative net income but complete data should have high data_confidence."""
        distressed_income = {
            "revenue": 1000.0, "gross_profit": 400.0,
            "operating_income": -50.0, "net_income": -100.0,
        }
        score = compute_data_confidence(
            income_row=distressed_income,
            balance_row=self._full_balance(),
            ratios_row={},
            n_annual_periods=3,
            periods_since_last_filing=0,
        )
        healthy_income = {
            "revenue": 1000.0, "gross_profit": 400.0,
            "operating_income": 200.0, "net_income": 100.0,
        }
        score_healthy = compute_data_confidence(
            income_row=healthy_income,
            balance_row=self._full_balance(),
            ratios_row={},
            n_annual_periods=3,
            periods_since_last_filing=0,
        )
        # Both should have same score — distress doesn't penalize
        assert score == score_healthy, (
            f"Distressed company data_confidence ({score}) should equal "
            f"healthy company data_confidence ({score_healthy}) when data is equally complete"
        )

    def test_stale_data_lower_confidence(self):
        # 5 periods since filing — very stale
        score_stale = compute_data_confidence(
            income_row=self._full_income(),
            balance_row=self._full_balance(),
            ratios_row=self._full_ratios(),
            n_annual_periods=5,
            periods_since_last_filing=5,
        )
        score_fresh = compute_data_confidence(
            income_row=self._full_income(),
            balance_row=self._full_balance(),
            ratios_row=self._full_ratios(),
            n_annual_periods=5,
            periods_since_last_filing=0,
        )
        assert score_stale < score_fresh, "Stale data should have lower confidence than fresh data"


