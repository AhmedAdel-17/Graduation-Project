class TestSignalCoherence:

    def test_perfect_coherence_no_deductions(self):
        # Consistent data: ROE > 0, NM > 0, DuPont holds
        nm = 0.10
        at = 0.5
        em = 2.5
        roe = nm * at * em  # = 0.125 — DuPont identity holds
        ratios = {
            "roe": roe, "net_margin": nm,
            "asset_turnover": at, "equity_multiplier": em,
            "dupont_3factor": roe,
            "current_ratio": 1.5,
        }
        score, reasons = FinancialCalculator.compute_signal_coherence(ratios)
        assert score == 100
        assert reasons == []

    def test_roe_margin_inconsistency(self):
        # ROE positive but net_margin negative — mathematical impossibility
        ratios = {
            "roe": 0.10, "net_margin": -0.05,
            "asset_turnover": 1.0, "equity_multiplier": 2.0,
            "dupont_3factor": None,
        }
        score, reasons = FinancialCalculator.compute_signal_coherence(ratios)
        assert score == 85  # −15 deduction
        assert any("ROE is positive but net_margin is negative" in r for r in reasons)

    def test_dupont_identity_failure(self):
        # DuPont identity fails: NM × AT × EM ≠ ROE
        nm = 0.10
        at = 0.5
        em = 2.5
        dp3 = nm * at * em  # = 0.125
        roe = 0.20  # Claimed ROE is 20%, but DuPont says 12.5%
        ratios = {
            "roe": roe, "net_margin": nm,
            "asset_turnover": at, "equity_multiplier": em,
            "dupont_3factor": dp3,
        }
        score, reasons = FinancialCalculator.compute_signal_coherence(ratios)
        assert score == 90  # −10 deduction
        assert any("DuPont identity fails" in r for r in reasons)

    def test_current_ratio_cross_source_divergence(self):
        # CSV says 1.5 but balance sheet computes 2.5 (67% divergence)
        ratios = {
            "roe": 0.10, "net_margin": 0.05,
            "current_ratio": 1.5,  # CSV value
        }
        score, reasons = FinancialCalculator.compute_signal_coherence(
            ratios,
            current_ratio_csv=1.5,
            current_assets=500.0,
            current_liabilities=200.0,  # Computes to 2.5 — 67% divergence from 1.5
        )
        assert score == 85  # −15 deduction
        assert any("Current ratio divergence" in r for r in reasons)

    def test_no_coverage_penalty_for_missing_optional_fields(self):
        # P/E and P/B missing should NOT penalize signal_coherence
        ratios = {
            "roe": 0.10, "net_margin": 0.10,
            "asset_turnover": 0.5, "equity_multiplier": 2.0,
            "dupont_3factor": 0.10,  # Matches ROE
            "pe_ratio": None,   # Missing — should NOT penalize
            "pb_ratio": None,   # Missing — should NOT penalize
        }
        score, reasons = FinancialCalculator.compute_signal_coherence(ratios)
        assert score == 100  # No deduction for missing optional coverage


